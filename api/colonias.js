// Quita acentos y pasa a minúsculas para que "angeles" encuentre "Los Ángeles"
function normalizar(texto) {
  return texto.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
}

function buscarColonias(texto = '') {
  const buscado = normalizar(texto);
  if (buscado === '') return COLONIAS;
  return COLONIAS.filter((c) => normalizar(c).includes(buscado));
}

module.exports = { COLONIAS, buscarColonias, normalizar };
